"""SQL de flujos de liquidez: lo que entra y sale de cada protocolo y pool, en USD.

Una fila por acción que mete o saca capital. Los AMMs salen de result_scf_lp_tx, ya valorizados
con sus reglas de dos lados. Blend, XOXNO Lending y DeFindex son de un solo token y se valorizan
acá con la misma regla de precio (último precio de hasta FFILL_DAYS días antes de la acción).

flow_type separa lo que no se suma con la liquidez depositada:
- liquidity: add/remove de AMMs, supply/withdraw de Blend, deposit/withdraw de vaults DeFindex.
- credit: borrow (sale del pool) y repay (vuelve). Deuda, no depósitos.
- backstop: depósitos y retiros del backstop de Blend. Su token es el LP de Comet BLND-USDC, que
  no tiene precio y fue atacado el 2026-08-25: se cuenta en acciones y direcciones, sin USD.
flash_loan no es flujo: se pide y se devuelve en la misma transacción.

XOXNO Lending (verificado el 2026-10-23 con las piernas de cada transacción): multiply es la
pierna del préstamo (el depósito sale aparte como supply) y migrate_from_blend la deuda que llega
desde Blend (el colateral también sale como supply). swap_debt cambia una deuda por otra en dos
piernas sin dirección neta, y flash_position es un flash loan: no son flujo. XOXNO no tiene pool
en la capa; el pool de la fila es el controller.
"""
import activity_sql
import prices_sql

lit = activity_sql.lit
FLOW_TX = 'dune.paltalabs.result_scf_flow_tx'
# (layer action, flow_type, direction) for the single-token protocols.
SINGLE_TOKEN_FLOWS = [
    ('supply', 'liquidity', 'in'), ('supply_collateral', 'liquidity', 'in'),
    ('withdraw', 'liquidity', 'out'), ('withdraw_collateral', 'liquidity', 'out'),
    ('borrow', 'credit', 'out'), ('repay', 'credit', 'in'),
    ('backstop_deposit', 'backstop', 'in'), ('backstop_withdraw', 'backstop', 'out'),
    ('vault_deposit', 'liquidity', 'in'), ('vault_withdraw', 'liquidity', 'out'),
    # XOXNO Lending legs beyond the ones it shares with Blend.
    ('close_withdraw', 'liquidity', 'out'), ('swap_collateral_withdraw', 'liquidity', 'out'),
    ('repay_collateral_withdraw', 'liquidity', 'out'),
    ('multiply', 'credit', 'out'), ('migrate_from_blend', 'credit', 'out'),
    ('repay_collateral_repay', 'credit', 'in'), ('repay_collateral_net', 'credit', 'in'),
]
SINGLE_TOKEN_PROTOCOLS = ('blend', 'xoxno_lending', 'defindex')


def single_token_layers():
    actions = lit(a for a, _, _ in SINGLE_TOKEN_FLOWS)
    where = (f"row_kind = 'activity' AND protocol IN ({lit(SINGLE_TOKEN_PROTOCOLS)}) "
             f"AND action IN ({actions})")
    columns = 'protocol, contract_id, closed_at, tx_hash, user_address, action, pool, token_a, amount_a'
    return '\nUNION ALL\n'.join(f'SELECT {columns} FROM {t(p)} WHERE {where}'
                                for p in SINGLE_TOKEN_PROTOCOLS
                                for t in (activity_sql.archive_table, activity_sql.live_table))


def flow_tx():
    mapping = ', '.join(f"('{a}', '{f}', '{d}')" for a, f, d in SINGLE_TOKEN_FLOWS)
    return f"""-- Generated by scripts/flows_sql.py. Liquidity flows: one row per action that moves capital in or out.
WITH tokens AS (
{prices_sql.token_values()}
), flows AS (
  SELECT * FROM (VALUES {mapping}) AS t(action, flow_type, direction)
), single AS (
  SELECT s.*, f.flow_type, f.direction, CAST(s.closed_at AT TIME ZONE 'UTC' AS DATE) AS day,
         ROW_NUMBER() OVER (ORDER BY s.closed_at, s.tx_hash, s.user_address, s.action, s.pool, s.amount_a) AS flow_row
  FROM (
{single_token_layers()}
  ) s
  JOIN flows f ON f.action = s.action
), valued AS (
  SELECT s.flow_row,
         ABS(CAST(s.amount_a AS DOUBLE)) * power(10, 7 - COALESCE(t.decimals, 7)) AS token_amount,
         max_by(p.price_usd, p.day) AS price_usd
  FROM single s
  LEFT JOIN tokens t ON t.token = s.token_a
  LEFT JOIN {prices_sql.PRICES} p ON s.flow_type <> 'backstop' AND p.token = s.token_a
   AND p.day <= s.day AND p.day >= s.day - INTERVAL '{prices_sql.FFILL_DAYS}' DAY
  GROUP BY s.flow_row, s.amount_a, t.decimals
)
SELECT s.protocol, s.contract_id, COALESCE(s.pool, s.contract_id) AS pool, s.closed_at, s.day, s.tx_hash, s.user_address,
       substr(s.user_address, 1, 1) AS address_type, s.action, s.flow_type, s.direction,
       s.token_a AS token, v.token_amount, v.price_usd,
       CASE WHEN s.flow_type = 'backstop' THEN NULL ELSE v.token_amount * v.price_usd END AS usd_value,
       'single' AS usd_method,
       CASE WHEN s.flow_type = 'backstop' THEN 'excluded'
            WHEN v.price_usd IS NOT NULL OR COALESCE(v.token_amount, 0) = 0 THEN 'priced'
            ELSE 'unpriced' END AS valuation,
       CURRENT_TIMESTAMP AS refreshed_at
FROM single s LEFT JOIN valued v ON v.flow_row = s.flow_row
UNION ALL
SELECT protocol, contract_id, pool, closed_at, day, tx_hash, user_address,
       substr(user_address, 1, 1), action, 'liquidity', CASE direction WHEN 'add' THEN 'in' ELSE 'out' END,
       CAST(NULL AS VARCHAR), CAST(NULL AS DOUBLE), CAST(NULL AS DOUBLE),
       CASE WHEN valuation = 'no_tokens' THEN NULL ELSE usd_total END, usd_method, valuation, CURRENT_TIMESTAMP
FROM {prices_sql.LP_TX}
WHERE direction IN ('add', 'remove')
"""


METRICS = {'flow_tx': flow_tx}
