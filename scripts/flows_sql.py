"""SQL de flujos de liquidez: lo que entra y sale de cada protocolo y pool, en USD.

Una fila por acción que mete o saca capital. Los AMMs salen de result_scf_lp_tx, ya valorizados
con sus reglas de dos lados. Blend, XOXNO Lending y DeFindex son de un solo token y se valorizan
acá con la misma regla de precio (último precio de hasta FFILL_DAYS días antes de la acción).

flow_type separa lo que no se suma con la liquidez depositada:
- liquidity: add/remove de AMMs, supply/withdraw de Blend, deposit/withdraw de vaults DeFindex.
- credit: borrow (sale del pool) y repay (vuelve). Deuda, no depósitos.
- backstop: depósitos y retiros del backstop de Blend. Su token es el LP de Comet BLND-USDC, que
  no tiene precio y fue atacado el 2026-08-25: se cuenta en acciones y direcciones, sin USD.
flash_loan no es flujo: se pide y se devuelve en la misma transacción.

XOXNO Lending (verificado el 2026-10-23 con las piernas de cada transacción): multiply es la
pierna del préstamo (el depósito sale aparte como supply) y migrate_from_blend la deuda que llega
desde Blend (el colateral también sale como supply). swap_debt cambia una deuda por otra en dos
piernas sin dirección neta, y flash_position es un flash loan: no son flujo. XOXNO no tiene pool
en la capa; el pool de la fila es el controller.
"""
import activity_sql
import prices_sql

lit = activity_sql.lit
FLOW_TX = 'dune.paltalabs.result_scf_flow_tx'
FLOWS_PERIODS = 'dune.paltalabs.result_scf_flows_periods'
MIGRATIONS = 'dune.paltalabs.result_scf_migrations'
MIN_PRICED_SHARE = 0.95       # flow_price_coverage fails a protocol under this share, last 90 days
# (layer action, flow_type, direction) for the single-token protocols.
SINGLE_TOKEN_FLOWS = [
    ('supply', 'liquidity', 'in'), ('supply_collateral', 'liquidity', 'in'),
    ('withdraw', 'liquidity', 'out'), ('withdraw_collateral', 'liquidity', 'out'),
    ('borrow', 'credit', 'out'), ('repay', 'credit', 'in'),
    ('backstop_deposit', 'backstop', 'in'), ('backstop_withdraw', 'backstop', 'out'),
    ('vault_deposit', 'liquidity', 'in'), ('vault_withdraw', 'liquidity', 'out'),
    # XOXNO Lending legs beyond the ones it shares with Blend.
    ('close_withdraw', 'liquidity', 'out'), ('swap_collateral_withdraw', 'liquidity', 'out'),
    ('repay_collateral_withdraw', 'liquidity', 'out'),
    ('multiply', 'credit', 'out'), ('migrate_from_blend', 'credit', 'out'),
    ('repay_collateral_repay', 'credit', 'in'), ('repay_collateral_net', 'credit', 'in'),
]
SINGLE_TOKEN_PROTOCOLS = ('blend', 'xoxno_lending', 'defindex')
MIGRATION_DAYS = 7           # decided 2026-10-23: 76% of the 30-day cases and 80% of their USD


def single_token_layers():
    actions = lit(a for a, _, _ in SINGLE_TOKEN_FLOWS)
    where = (f"row_kind = 'activity' AND protocol IN ({lit(SINGLE_TOKEN_PROTOCOLS)}) "
             f"AND action IN ({actions})")
    columns = 'protocol, contract_id, closed_at, tx_hash, user_address, action, pool, token_a, amount_a'
    return '\nUNION ALL\n'.join(f'SELECT {columns} FROM {t(p)} WHERE {where}'
                                for p in SINGLE_TOKEN_PROTOCOLS
                                for t in (activity_sql.archive_table, activity_sql.live_table))


def flow_tx():
    mapping = ', '.join(f"('{a}', '{f}', '{d}')" for a, f, d in SINGLE_TOKEN_FLOWS)
    return f"""-- Generated by scripts/flows_sql.py. Liquidity flows: one row per action that moves capital in or out.
WITH tokens AS (
{prices_sql.token_values()}
), flows AS (
  SELECT * FROM (VALUES {mapping}) AS t(action, flow_type, direction)
), single AS (
  SELECT s.*, f.flow_type, f.direction, CAST(s.closed_at AT TIME ZONE 'UTC' AS DATE) AS day,
         ROW_NUMBER() OVER (ORDER BY s.closed_at, s.tx_hash, s.user_address, s.action, s.pool, s.amount_a) AS flow_row
  FROM (
{single_token_layers()}
  ) s
  JOIN flows f ON f.action = s.action
), valued AS (
  SELECT s.flow_row,
         ABS(CAST(s.amount_a AS DOUBLE)) * power(10, 7 - COALESCE(t.decimals, 7)) AS token_amount,
         max_by(p.price_usd, p.day) AS price_usd
  FROM single s
  LEFT JOIN tokens t ON t.token = s.token_a
  LEFT JOIN {prices_sql.PRICES} p ON s.flow_type <> 'backstop' AND p.token = s.token_a
   AND p.day <= s.day AND p.day >= s.day - INTERVAL '{prices_sql.FFILL_DAYS}' DAY
  GROUP BY s.flow_row, s.amount_a, t.decimals
)
SELECT s.protocol, s.contract_id, COALESCE(s.pool, s.contract_id) AS pool, s.closed_at, s.day, s.tx_hash, s.user_address,
       substr(s.user_address, 1, 1) AS address_type, s.action, s.flow_type, s.direction,
       s.token_a AS token, v.token_amount, v.price_usd,
       CASE WHEN s.flow_type = 'backstop' THEN NULL ELSE v.token_amount * v.price_usd END AS usd_value,
       'single' AS usd_method,
       CASE WHEN s.flow_type = 'backstop' THEN 'excluded'
            WHEN v.price_usd IS NOT NULL OR COALESCE(v.token_amount, 0) = 0 THEN 'priced'
            ELSE 'unpriced' END AS valuation,
       CURRENT_TIMESTAMP AS refreshed_at
FROM single s LEFT JOIN valued v ON v.flow_row = s.flow_row
UNION ALL
SELECT protocol, contract_id, pool, closed_at, day, tx_hash, user_address,
       substr(user_address, 1, 1), action, 'liquidity', CASE direction WHEN 'add' THEN 'in' ELSE 'out' END,
       CAST(NULL AS VARCHAR), CAST(NULL AS DOUBLE), CAST(NULL AS DOUBLE),
       CASE WHEN valuation = 'no_tokens' THEN NULL ELSE usd_total END, usd_method, valuation, CURRENT_TIMESTAMP
FROM {prices_sql.LP_TX}
WHERE direction IN ('add', 'remove')
"""


def flows_periods():
    """In, out and net USD per calendar week and month (UTC) at three levels: each pool, each
    protocol (pool 'all') and the ecosystem (protocol 'all protocols'). G and C addresses are
    separate rows; the ecosystem keeps only G, since contracts (DeFindex strategies above all)
    move into another protocol what already entered one and would count it twice."""
    return f"""-- Liquidity flows per week and month: in, out and net USD per pool, protocol and ecosystem.
WITH tx AS (SELECT * FROM {FLOW_TX} WHERE day < CURRENT_DATE),
grains AS (
  SELECT 'week' AS grain, CAST(date_trunc('week', day) AS DATE) AS period_start, * FROM tx
  UNION ALL
  SELECT 'month', CAST(date_trunc('month', day) AS DATE), * FROM tx
), levels AS (
  SELECT grain, period_start, protocol, pool, flow_type, address_type, direction, user_address, usd_value, valuation FROM grains
  UNION ALL
  SELECT grain, period_start, protocol, 'all', flow_type, address_type, direction, user_address, usd_value, valuation FROM grains
  UNION ALL
  SELECT grain, period_start, 'all protocols', 'all', flow_type, address_type, direction, user_address, usd_value, valuation
  FROM grains WHERE address_type = 'G'
)
SELECT grain, period_start, protocol, pool, flow_type, address_type,
       COUNT(DISTINCT user_address) AS addresses,
       COUNT(DISTINCT CASE WHEN direction = 'in' THEN user_address END) AS addresses_in,
       COUNT(DISTINCT CASE WHEN direction = 'out' THEN user_address END) AS addresses_out,
       COUNT_IF(direction = 'in') AS actions_in, COUNT_IF(direction = 'out') AS actions_out,
       SUM(usd_value) FILTER (WHERE direction = 'in') AS usd_in,
       SUM(usd_value) FILTER (WHERE direction = 'out') AS usd_out,
       COALESCE(SUM(usd_value) FILTER (WHERE direction = 'in'), 0) - COALESCE(SUM(usd_value) FILTER (WHERE direction = 'out'), 0) AS usd_net,
       CAST(COUNT_IF(valuation = 'priced') AS DOUBLE) / NULLIF(COUNT_IF(valuation NOT IN ('excluded', 'no_tokens')), 0) AS priced_action_share,
       date_add(grain, 1, period_start) <= CURRENT_DATE AS is_complete
FROM levels GROUP BY 1, 2, 3, 4, 5, 6
"""


def migrations():
    """For every liquidity withdrawal of a G address in protocol A, the first liquidity deposit of
    the same address in another protocol B within MIGRATION_DAYS after it. Only G addresses: a
    contract that moves funds between protocols is a strategy or a router, not a user choosing a
    protocol (3 contract migrations in 30 days against 1.179 of wallets, 2026-10-22). The amount
    that could have migrated is the smaller of the two sides. A deposit counts once, for the
    closest withdrawal before it: without that, 429 SushiSwap -> Aquarius matches of 6 addresses
    reused the same deposits (2026-10-23). Withdrawals newer than the window are left out until
    it closes."""
    return f"""-- Liquidity migrations: a wallet withdraws from one protocol and deposits in another within {MIGRATION_DAYS} days.
WITH f AS (
  SELECT protocol, pool, closed_at, tx_hash, user_address, direction, usd_value
  FROM {FLOW_TX}
  WHERE flow_type = 'liquidity' AND address_type = 'G'
), outs AS (
  SELECT * FROM f WHERE direction = 'out' AND closed_at < CURRENT_TIMESTAMP - INTERVAL '{MIGRATION_DAYS}' DAY
), ins AS (SELECT * FROM f WHERE direction = 'in'),
matched AS (
  SELECT o.protocol AS from_protocol, o.pool AS from_pool, o.closed_at AS out_at, o.tx_hash AS out_tx,
         o.user_address, o.usd_value AS usd_out,
         min_by(CAST(ROW(i.protocol, i.pool, i.closed_at, i.tx_hash, i.usd_value)
                AS ROW(protocol varchar, pool varchar, closed_at timestamp(3) with time zone, tx_hash varchar, usd_value double)),
                ROW(i.closed_at, i.tx_hash)) AS first_in
  FROM outs o
  JOIN ins i ON i.user_address = o.user_address AND i.protocol <> o.protocol
   AND i.closed_at >= o.closed_at AND i.closed_at <= o.closed_at + INTERVAL '{MIGRATION_DAYS}' DAY
  GROUP BY 1, 2, 3, 4, 5, 6
), closest AS (
  SELECT *, ROW_NUMBER() OVER (PARTITION BY user_address, first_in.protocol, first_in.tx_hash, first_in.closed_at
                               ORDER BY out_at DESC, out_tx DESC) AS rn
  FROM matched
)
SELECT from_protocol, from_pool, first_in.protocol AS to_protocol, first_in.pool AS to_pool, user_address,
       out_at, first_in.closed_at AS in_at, CAST(out_at AT TIME ZONE 'UTC' AS DATE) AS out_day,
       out_tx, first_in.tx_hash AS in_tx, out_tx = first_in.tx_hash AS same_tx,
       date_diff('second', out_at, first_in.closed_at) AS seconds_between,
       usd_out, first_in.usd_value AS usd_in, LEAST(usd_out, first_in.usd_value) AS usd_migrated,
       CURRENT_TIMESTAMP AS refreshed_at
FROM closest WHERE rn = 1
"""


def validation_checks():
    """Checks for result_scf_users_validation, failures = 0 when they pass. Price coverage counts
    the protocols whose priced share of the last 90 days falls under MIN_PRICED_SHARE."""
    single_rows = single_token_layers().replace(
        'SELECT protocol, contract_id, closed_at, tx_hash, user_address, action, pool, token_a, amount_a', 'SELECT 1 AS one')
    return f"""SELECT 'flow_tx_vs_layers', ABS((SELECT COUNT(*) FROM {FLOW_TX})
  - (SELECT COUNT(*) FROM ({single_rows}) AS x)
  - (SELECT COUNT(*) FROM {prices_sql.LP_TX} WHERE direction IN ('add', 'remove')))
UNION ALL
SELECT 'flow_price_coverage', COUNT(*) FROM (
  SELECT protocol FROM {FLOW_TX}
  WHERE day >= CURRENT_DATE - INTERVAL '90' DAY AND valuation NOT IN ('excluded', 'no_tokens')
  GROUP BY 1 HAVING CAST(COUNT_IF(valuation = 'priced') AS DOUBLE) / COUNT(*) < {MIN_PRICED_SHARE}
)
UNION ALL
SELECT 'flows_periods_vs_tx', ABS((SELECT SUM(actions_in + actions_out) FROM {FLOWS_PERIODS}
  WHERE grain = 'month' AND pool = 'all' AND protocol <> 'all protocols')
  - (SELECT COUNT(*) FROM {FLOW_TX} WHERE day < CURRENT_DATE))
UNION ALL
SELECT 'migrations_out_of_window', COUNT(*) FROM {MIGRATIONS}
WHERE from_protocol = to_protocol OR seconds_between < 0 OR seconds_between > {MIGRATION_DAYS} * 86400
   OR user_address NOT LIKE 'G%'
UNION ALL
SELECT 'migrations_reused_deposits', COUNT(*) - COUNT(DISTINCT user_address || to_protocol || in_tx || CAST(in_at AS VARCHAR)) FROM {MIGRATIONS}"""



# ---- chart sources -------------------------------------------------------------------------------
# Matview executions only persist a row count, so each chart reads its matview with its own SELECT.

def chart_flows_ecosystem(grain):
    return f"""-- Chart source: liquidity in, out and net USD of the ecosystem per complete calendar {grain}, wallets (G) only.
-- usd_out_negative draws withdrawals below the axis.
SELECT period_start, usd_in, -usd_out AS usd_out_negative, usd_out, usd_net, addresses, addresses_in, addresses_out
FROM {FLOWS_PERIODS}
WHERE grain = '{grain}' AND is_complete AND protocol = 'all protocols' AND pool = 'all' AND flow_type = 'liquidity'
  AND address_type = 'G' AND period_start >= {activity_sql.chart_since(grain)}
ORDER BY period_start
"""


def chart_flows_protocol():
    return f"""-- Chart source: net liquidity flow per protocol and complete calendar month, wallets (G) only.
SELECT period_start, protocol, usd_in, usd_out, usd_net, addresses
FROM {FLOWS_PERIODS}
WHERE grain = 'month' AND is_complete AND protocol <> 'all protocols' AND pool = 'all' AND flow_type = 'liquidity'
  AND address_type = 'G' AND period_start >= {activity_sql.chart_since('month')}
ORDER BY period_start, protocol
"""


def chart_flows_pools():
    return f"""-- Chart source: top 20 pools and vaults by liquidity moved (in + out), last 90 complete days, G and C.
WITH p AS (
  SELECT protocol, pool,
         SUM(usd_value) FILTER (WHERE direction = 'in') AS usd_in,
         SUM(usd_value) FILTER (WHERE direction = 'out') AS usd_out,
         COUNT(*) AS actions, COUNT(DISTINCT user_address) AS addresses,
         COUNT(DISTINCT CASE WHEN address_type = 'G' THEN user_address END) AS g_addresses
  FROM {FLOW_TX}
  WHERE flow_type = 'liquidity' AND day >= CURRENT_DATE - INTERVAL '90' DAY AND day < CURRENT_DATE
  GROUP BY 1, 2
)
SELECT protocol, pool, usd_in, usd_out, COALESCE(usd_in, 0) - COALESCE(usd_out, 0) AS usd_net,
       COALESCE(usd_in, 0) + COALESCE(usd_out, 0) AS usd_moved, actions, addresses, g_addresses
FROM p ORDER BY usd_moved DESC LIMIT 20
"""


def chart_credit():
    return f"""-- Chart source: borrowed and repaid USD per lending protocol and complete calendar month, G and C.
SELECT period_start, protocol, SUM(usd_out) AS usd_borrowed, SUM(usd_in) AS usd_repaid,
       COALESCE(SUM(usd_in), 0) - COALESCE(SUM(usd_out), 0) AS usd_net_repaid,
       SUM(addresses) AS addresses
FROM {FLOWS_PERIODS}
WHERE grain = 'month' AND is_complete AND protocol <> 'all protocols' AND pool = 'all' AND flow_type = 'credit'
GROUP BY 1, 2 ORDER BY 1, 2
"""


def chart_migration_pairs():
    return f"""-- Chart source: liquidity migrations between protocols ({MIGRATION_DAYS}-day window), all time, wallets (G).
SELECT from_protocol, to_protocol, COUNT(*) AS migrations, COUNT(DISTINCT user_address) AS addresses,
       COUNT_IF(NOT same_tx) AS two_step, COUNT_IF(same_tx) AS same_transaction,
       SUM(usd_migrated) AS usd_migrated, SUM(usd_migrated) FILTER (WHERE NOT same_tx) AS usd_two_step,
       approx_percentile(seconds_between, 0.5) / 3600.0 AS median_hours,
       MIN(out_day) AS first_day, MAX(out_day) AS last_day
FROM {MIGRATIONS}
GROUP BY 1, 2 ORDER BY migrations DESC
"""


def chart_migrations_monthly():
    return f"""-- Chart source: migrations per complete calendar month, split by how they happened, wallets (G).
-- same transaction: an app withdrew and deposited in one step; two steps: the wallet did it in two transactions.
SELECT CAST(date_trunc('month', out_day) AS DATE) AS period_start,
       CASE WHEN same_tx THEN 'same transaction (app)' ELSE 'two steps (wallet)' END AS kind,
       COUNT(*) AS migrations, COUNT(DISTINCT user_address) AS addresses, SUM(usd_migrated) AS usd_migrated
FROM {MIGRATIONS}
WHERE out_day < CAST(date_trunc('month', CURRENT_DATE) AS DATE)
GROUP BY 1, 2 ORDER BY 1, 2
"""


def chart_migrations_two_step():
    return f"""-- Chart source: two-step migrations per complete calendar month and route, top 6 routes by count, rest as other.
WITH m AS (
  SELECT CAST(date_trunc('month', out_day) AS DATE) AS period_start, from_protocol || ' > ' || to_protocol AS route, user_address, usd_migrated
  FROM {MIGRATIONS}
  WHERE NOT same_tx AND out_day < CAST(date_trunc('month', CURRENT_DATE) AS DATE)
), top AS (
  SELECT route FROM m GROUP BY 1 ORDER BY COUNT(*) DESC LIMIT 6
)
SELECT period_start, CASE WHEN route IN (SELECT route FROM top) THEN route ELSE 'other' END AS route,
       COUNT(*) AS migrations, COUNT(DISTINCT user_address) AS addresses, SUM(usd_migrated) AS usd_migrated
FROM m GROUP BY 1, 2 ORDER BY 1, 2
"""


def chart_flow_coverage():
    return f"""-- Chart source: share of flow actions valued in USD per protocol and flow type, last 90 complete days.
SELECT protocol, flow_type, COUNT(*) AS actions, COUNT_IF(valuation = 'priced') AS priced,
       COUNT_IF(valuation = 'unpriced') AS unpriced, COUNT_IF(valuation IN ('excluded', 'no_tokens')) AS not_valued,
       CAST(COUNT_IF(valuation = 'priced') AS DOUBLE) / NULLIF(COUNT_IF(valuation NOT IN ('excluded', 'no_tokens')), 0) AS priced_share
FROM {FLOW_TX}
WHERE day >= CURRENT_DATE - INTERVAL '90' DAY AND day < CURRENT_DATE
GROUP BY 1, 2 ORDER BY 1, 2
"""


